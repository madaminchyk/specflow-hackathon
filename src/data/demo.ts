export function createDemo(): Project {
  const p = blankProject('Бронирование переговорных');
  p.mode = 'demo';
  p.processingStatus = 'ready';
  p.summary =
    'Сервис бронирования переговорных для одного офиса: корпоративный вход, поиск комнат, управление бронями и уведомления. Требуется согласовать горизонт бронирования и три открытых вопроса.';
  p.segments = lines.map(([speakerName, text], i) => ({
    id: `seg-${i + 1}`,
    speakerId: speakerName === 'Заказчик' ? 'client' : 'analyst',
    speakerName,
    startMs: i * 17000,
    endMs: i * 17000 + 15000,
    text,
    timing: 'exact',
  }));
  p.roles = [
    {
      id: 'employee',
      name: 'Сотрудник',
      description: 'Находит и бронирует переговорную для встречи.',
      goals: ['Найти подходящую комнату', 'Управлять своими бронированиями'],
    },
    {
      id: 'admin',
      name: 'Администратор',
      description: 'Поддерживает справочник комнат и управляет бронями.',
      goals: ['Актуальные данные переговорных', 'Разрешение организационных конфликтов'],
    },
  ];
  p.requirements = seeds.map((s, i) => ({
    ...newRequirement(),
    id: `REQ-${String(i + 1).padStart(3, '0')}`,
    title: s.title,
    description: s.description,
    type: s.type,
    sourceSegmentIds: s.sources.map((n) => `seg-${n}`),
    roleIds: s.role ? [s.role] : [],
    confidence: s.confidence ?? 0.92,
    manuallyCreated: false,
    acceptanceCriteria: s.criteria ?? [],
    conditions: s.conditions ?? [],
    userStory: s.story,
    status: s.type === 'openQuestion' || s.confidence ? 'needsClarification' : 'draft',
    priority: s.type === 'openQuestion' ? 'could' : 'must',
    rationale:
      s.type === 'openQuestion'
        ? 'В разговоре явно оставлен вопрос без окончательного ответа.'
        : s.type === 'businessRule'
          ? 'Источник задаёт правило, которое ограничивает поведение системы.'
          : 'Участник явно описывает требуемое поведение или условие. Критерии приёмки предложены для проверки.',
  }));
  p.scenarios = [
    {
      id: 'scenario-1',
      title: 'Найти подходящую комнату',
      roleId: 'employee',
      steps: [
        'Войти в корпоративную учётную запись',
        'Выбрать дату, интервал и число участников',
        'Уточнить оборудование',
        'Открыть свободную комнату',
      ],
      relatedRequirementIds: ['REQ-001', 'REQ-002', 'REQ-003'],
    },
    {
      id: 'scenario-2',
      title: 'Забронировать переговорную',
      roleId: 'employee',
      steps: [
        'Выбрать комнату',
        'Указать время и название встречи',
        'Подтвердить бронь',
        'Получить письмо и увидеть бронь в календаре',
      ],
      relatedRequirementIds: ['REQ-004', 'REQ-005', 'REQ-008'],
    },
    {
      id: 'scenario-3',
      title: 'Отменить встречу',
      roleId: 'employee',
      steps: [
        'Открыть свою бронь',
        'Нажать «Отменить»',
        'Подтвердить действие',
        'Проверить освобождение интервала',
      ],
      relatedRequirementIds: ['REQ-007', 'REQ-008'],
    },
  ];
  p.conflicts = [
    {
      id: 'conflict-1',
      title: 'На сколько дней вперёд можно бронировать?',
      description:
        'Сначала заказчик назвал 30 дней, затем ограничил срок 14 днями. Последняя реплика не считается автоматическим утверждением нового правила.',
      sourceSegmentIds: ['seg-11', 'seg-25'],
      requirementIds: ['REQ-006', 'REQ-017'],
      severity: 'high',
      status: 'open',
    },
  ];
  return ProjectSchema.parse(p);
}
